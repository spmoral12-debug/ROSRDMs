# -*- coding: utf-8 -*-
"""
Packs unpacked_lobby.py into remote-lobby.py and all hot-lobby-*.py files
using the engine's exact keystream cipher, and updates the SHA256 checksum.
"""

import os, zlib, hashlib, base64, glob

UNPACKED = r'C:\Users\seanj\AppData\Local\DieHardROSHook\updates\unpacked_lobby.py'
REMOTE_LOBBY = r'C:\DieHardROS\local_update\hot\remote-lobby.py'
SHA_FILE = r'C:\DieHardROS\local_update\hot\remote-lobby.py.sha256'
HOT_DIR = r'C:\Users\seanj\AppData\Local\DieHardROSHook\updates'

KEY_HEX = '2a8ec34ed7c4baa57c7b5e4adef0f454f8f854d809daa14616db06b2eac10809'
KEY = bytes.fromhex(KEY_HEX)

print("Reading unpacked_lobby.py...")
with open(UNPACKED, 'rb') as f:
    src_bytes = f.read()

print("Compressing (%d bytes)..." % len(src_bytes))
compressed = zlib.compress(src_bytes, 9)
size = len(compressed)

print("Encrypting with keystream...")
i = 0
c = 0
parts = []
while i < size:
    chunk = compressed[i:i + 65536]
    blocks = (len(chunk) + 31) // 32
    ks = b''.join([hashlib.sha256(KEY + str(c + k).encode('ascii')).digest() for k in range(blocks)])[:len(chunk)]
    c += blocks
    xored = bytes(bytearray(a ^ b for a, b in zip(chunk, ks)))
    parts.append(xored)
    i += 65536

encrypted_blob = b''.join(parts)
b64 = base64.b64encode(encrypted_blob).decode('ascii')
chunks = [b64[j:j+4000] for j in range(0, len(b64), 4000)]
print("Total chunks: %d (b64 length: %d)" % (len(chunks), len(b64)))

# Build Python 2.7 / 3 compatible packed file
header = [
    '# DieHard ROS Online - packed hot patch. Generated by tools/pack_patch.py; do not edit by hand.',
    'import zlib as _dhz, hashlib as _dhh, base64 as _dhb',
    '_K = "%s".decode("hex")' % KEY_HEX,
    '_CO = "lobby_hot_patch"',
    '_B = [',
]
for chunk in chunks:
    header.append('    "%s",' % chunk)
header.append(']')
header.append('')

runner = '''def _dh_run():
    import time as _dht
    _t0 = _dht.time()
    raw = _dhb.b64decode("".join(_B))
    _t1 = _dht.time()
    parts = []
    i = 0
    c = 0
    size = len(raw)
    while i < size:
        chunk = raw[i:i + 65536]
        blocks = (len(chunk) + 31) // 32
        ks = "".join([_dhh.sha256(_K + str(c + k)).digest() for k in range(blocks)])[:len(chunk)]
        c += blocks
        hx = "%x" % (int(chunk.encode("hex"), 16) ^ int(ks.encode("hex"), 16))
        parts.append(("0" * (2 * len(chunk) - len(hx)) + hx).decode("hex"))
        i += 65536
    _t2 = _dht.time()
    src = _dhz.decompress("".join(parts))
    _t3 = _dht.time()
    code = compile(src, _CO, "exec")
    _t4 = _dht.time()
    exec code in globals()
    _t5 = _dht.time()
    try:
        _dhl = globals().get("log")
        if callable(_dhl):
            _dhl("local-hot-patch-timing", name=_CO, b64_ms=int(1000 * (_t1 - _t0)), xor_ms=int(1000 * (_t2 - _t1)),
                 unzip_ms=int(1000 * (_t3 - _t2)), compile_ms=int(1000 * (_t4 - _t3)), run_ms=int(1000 * (_t5 - _t4)),
                 bytes=len(src))
    except Exception:
        pass


_dh_run()
'''

packed_text = '\r\n'.join(header) + '\r\n' + runner
packed_bytes = packed_text.encode('utf-8')

base_dir = os.path.dirname(os.path.abspath(__file__))
dest_files = [
    os.path.join(base_dir, 'local_update', 'hot', 'remote-lobby.py'),
    os.path.join(base_dir, 'ROS_Redemption_Server_Package', 'local_update', 'hot', 'remote-lobby.py'),
    r'C:\DieHardROS\local_update\hot\remote-lobby.py',
    r'C:\DieHardROS\ROS-REDEMPTION\DieHardROS\local_update\hot\remote-lobby.py',
    r'C:\DieHardROS\ROS-REDEMPTION\DieHardROS\ROS_Redemption_Server_Package\local_update\hot\remote-lobby.py',
]

sha256_hash = hashlib.sha256(packed_bytes).hexdigest()
print("Computed SHA256:", sha256_hash)

for df in dest_files:
    try:
        os.makedirs(os.path.dirname(df), exist_ok=True)
        with open(df, 'wb') as f:
            f.write(packed_bytes)
        print("Written destination:", df)
        sha_p = df + '.sha256'
        with open(sha_p, 'w') as f:
            f.write(sha256_hash)
        print("Updated SHA:", sha_p)
    except Exception as ex:
        print("Skip destination %s: %s" % (df, ex))

# Write to all hot-lobby-*.py
for hf in glob.glob(os.path.join(HOT_DIR, 'hot-lobby-*.py')):
    try:
        with open(hf, 'wb') as f:
            f.write(packed_bytes)
        print("Written hot-lobby:", hf)
    except Exception as ex:
        print("Skip hot-lobby %s: %s" % (hf, ex))

print("PACKING COMPLETED SUCCESSFULLY!")

